#!/usr/bin/env python3
"""Reproduce the identity audit's network calls, retaining HTTP failures as data.

No structure is generated by this script. Existing raw files are not replaced;
use --refetch to save a new receipt directory alongside the initial receipts.
"""
import argparse
import datetime as dt
import hashlib
import json
from pathlib import Path
import urllib.request

BASE = Path(__file__).resolve().parent
PROPS = "MolecularFormula,MolecularWeight,ExactMass,IsomericSMILES,InChI,InChIKey,IUPACName,DefinedAtomStereoCount,UndefinedAtomStereoCount,DefinedBondStereoCount,UndefinedBondStereoCount"
PUG = "https://pubchem.ncbi.nlm.nih.gov/rest/pug"
SOURCES = {
    "cas_890654_03_2.json": f"{PUG}/compound/name/890654-03-2/property/{PROPS}/JSON",
    "s_me_dm4.json": f"{PUG}/compound/name/S-Me-DM4/property/{PROPS}/JSON",
    "correct_cid_properties.json": f"{PUG}/compound/cid/89493732/property/{PROPS}/JSON",
    "correct_key_properties.json": f"{PUG}/compound/inchikey/AYWIIXDQRUFQGH-SIDGEOBYSA-N/property/{PROPS}/JSON",
    "correct_cid_synonyms.json": f"{PUG}/compound/cid/89493732/synonyms/JSON",
    "correct_cid_sdf.sdf": f"{PUG}/compound/cid/89493732/SDF",
    "correct_cid_pugview.json": "https://pubchem.ncbi.nlm.nih.gov/rest/pug_view/data/compound/89493732/JSON",
    "pubchem_sme_substance.json": f"{PUG}/substance/sid/401073236/JSON",
    "old_cid_properties.json": f"{PUG}/compound/cid/11542407/property/{PROPS}/JSON",
    "old_cid_synonyms.json": f"{PUG}/compound/cid/11542407/synonyms/JSON",
    "dm4_parent_properties.json": f"{PUG}/compound/inchikey/JFCFGYGEYRIEBE-YVLHJLIDSA-N/property/{PROPS}/JSON",
    "gsrs_search_methyl_dm4.json": "https://gsrs.ncats.nih.gov/api/v1/substances/search?q=DM4",
    "gsrs_exact_sme_query.json": "https://gsrs.ncats.nih.gov/api/v1/substances/search?q=%22S-Me-DM4%22",
    "gsrs_exact_smethyl_query.json": "https://gsrs.ncats.nih.gov/api/v1/substances/search?q=%22S-METHYL%20DM4%22",
    "gsrs_sme_inchikey_query.json": "https://gsrs.ncats.nih.gov/api/v1/substances/search?q=%22AYWIIXDQRUFQGH-SIDGEOBYSA-N%22",
    "primary2010_pmc.html": "https://pmc.ncbi.nlm.nih.gov/articles/PMC2954514/",
    "primary2010_figure1.jpg": "https://cdn.ncbi.nlm.nih.gov/pmc/blobs/e52f/2954514/1fff72ba39ea/nihms225227f1.jpg",
    "primary2010_fulltext.xml": "https://www.ebi.ac.uk/europepmc/webservices/rest/PMC2954514/fullTextXML",
}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--refetch", action="store_true")
    args = parser.parse_args()
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = BASE / (f"raw_refetch_{stamp}" if args.refetch else "raw")
    out.mkdir(parents=True, exist_ok=True)
    receipt = []
    for name, url in SOURCES.items():
        row = {"url": url, "saved": str(out / name), "retrieved_utc": dt.datetime.now(dt.timezone.utc).isoformat()}
        if (out / name).exists():
            b = (out / name).read_bytes()
            row.update(action="existing_raw_retained", bytes=len(b), sha256=hashlib.sha256(b).hexdigest())
        else:
            try:
                with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "ADC research identity audit"}), timeout=35) as response:
                    b = response.read()
                    row.update(status=response.status, content_type=response.headers.get("Content-Type"))
                (out / name).write_bytes(b)
                row.update(action="fetched", bytes=len(b), sha256=hashlib.sha256(b).hexdigest())
            except Exception as exc:
                row.update(action="fetch_failed", error=str(exc))
                (out / (name + ".error.txt")).write_text(str(exc))
        receipt.append(row)
    (out / f"source_manifest_{stamp}.json").write_text(json.dumps(receipt, indent=2) + "\n")

if __name__ == "__main__":
    main()
